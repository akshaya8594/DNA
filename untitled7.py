from datetime import datetime

# Read the chat file
with open("/content/hostel_bois.txt", "r", encoding="utf-8") as file:
    lines = file.readlines()

messages = []
system_count = 0
media_count = 0
deleted_count = 0

for line in lines:
    line = line.strip()
    if line == "":
        continue

    # Skip continuation lines
    if len(line) < 8 or line[2] != "/" or line[5] != "/":
        continue

    try:
        timestamp, rest = line.split(" - ", 1)
        sender, message = rest.split(": ", 1)
    except ValueError:
        system_count += 1
        continue

    if message == "<Media omitted>":
        media_count += 1
    if message == "This message was deleted":
        deleted_count += 1

    try:
        dt_obj = datetime.strptime(timestamp, "%d/%m/%y, %H:%M")
    except ValueError:
        dt_obj = datetime.now()

    messages.append({
        "timestamp": timestamp,
        "datetime": dt_obj,
        "sender": sender,
        "message": message
    })

