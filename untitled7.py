response_data = []
for i in range(1, len(messages)):
    prev, curr = messages[i - 1], messages[i]
    if prev["sender"] == curr["sender"]: continue

    minutes = (curr["datetime"] - prev["datetime"]).total_seconds() / 60
    if minutes >= 0:
        response_data.append({"sender": curr["sender"], "previous_sender": prev["sender"], "minutes": minutes})

